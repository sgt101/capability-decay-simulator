function manifestFacts(file) {
  const m = JSON.parse(fs.readFileSync(path.resolve(paths.DATA, file), "utf8"));
  const first = m.experiments[0];
  const nx = m.studyParams[first.x].values.length, ny = m.studyParams[first.y].values.length;
  const runs = m.experiments.reduce((s, e) => s + (e.runs || 0), 0);
  return [
    m.experiments.length + " experiments",
    nx + " x " + ny + " grid",
    m.replicates + " replicates per cell",
    runs.toLocaleString("en-US") + " runs",
    // The horizon is in ticks; TICKS_PER_YEAR is 12. Stated in years because months in
    // the thousands mean nothing to a reader arriving cold.
    Math.round(m.horizon / 12) + "-year horizon",
  ];
}

