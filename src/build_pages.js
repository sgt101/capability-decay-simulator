// Assembles site/ — the simulator, the generated report browsers, and a landing page
// listing them, ready for GitHub Pages.
//
//   node src/build_pages.js
//
// The simulator is already a static page with no build step, so this exists for one
// reason: it loads ../data/world-model-data.js, a path that reaches OUT of the
// directory it sits in. Publishing src/ alone would silently drop the world model and
// leave the page on the generated BA graph — it degrades rather than failing, which is
// the worst way for this to go wrong. The copy flattens that one path.
//
// Deliberately NOT publishing the whole repository root. That would work (the relative
// paths resolve as-is) but the entry point would be /src/simulator.html and every
// source file would be served alongside it. A handful of named files is a smaller thing
// to reason about.
//
// Layout, which differs from the repository's and is why two paths get rewritten here:
//
//   site/index.html            generated from src/landing.template.html
//   site/simulator.html        src/simulator.html, ../data/ paths flattened
//   site/report.html etc.      doc/*.html, simulatorHref repointed at simulator.html
//   site/data/, engine.js ...  copied as-is
//
// The reports are OPTIONAL: they are built from results/, which is not in the
// repository, so a fresh clone publishes the simulator alone rather than failing.
