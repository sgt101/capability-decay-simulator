// The rewrite: every ../data/ script reference is flattened to data/, since site/ keeps
// data/ as a directory but has no parent to reach out of.
//
// Generalised over the whole prefix rather than naming one file, because naming one file
// is what broke: simulator.html gained ../data/cell-index.js and this rewrite still knew
// only about the world model, so the orphan check below — correctly — refused to publish
// a page whose second script would 404. A per-file rewrite has to be updated in lockstep
// with the page; a prefix rewrite does not.
//
// Still asserted rather than assumed. Rewriting nothing at all means the page has stopped
// reaching out of its directory, which either is a real change worth noticing or means
// this whole script is now unnecessary; either way, silence is the wrong answer.
const DATA_REF = /<script src="\.\.\/data\/([^"]+)"><\/script>/g;
const rewritten = [...html.matchAll(DATA_REF)].map((m) => m[1]);
if (!rewritten.length) {
  console.error(`[build_pages] simulator.html no longer loads anything from ../data/`);
  console.error(`  Either the data script paths changed — update ASSETS and this rewrite —`);
  console.error(`  or the page is self-contained now and build_pages.js has no job left.`);
  process.exit(1);
}
html = html.replace(DATA_REF, '<script src="data/$1"></script>');

// Every <script src> in the published page must exist in the published tree. This is
// the check that matters: the page loads its dependencies at runtime, so a missing one
// is not a build error, it is a broken site that still renders.
const referenced = [...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map((m) => m[1]);
const shipped = new Set(ASSETS.map(([, dest]) => dest));
const orphans = referenced.filter((r) => !shipped.has(r));
if (orphans.length) {
  console.error(`[build_pages] the page loads scripts that are not being published: ${orphans.join(", ")}`);
  process.exit(1);
}

fs.writeFileSync(path.join(OUT, "simulator.html"), html);
